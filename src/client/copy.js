/**
 * 设置页 ui.SettingsForm 的 labels：保存、保存中、保存失败、只读四条各页共用（form.*），「设置暂不可用」各页自己给。
 * @param {Function} t 词典函数（app.t）。
 * @param {string | undefined} failed 保存失败的原因；没失败时 undefined。
 * @param {string} unavailableKey 这一页「设置暂不可用」的词典键。
 * @returns {{save: string, saving: string, saveFailed: string, readOnly: string, unavailable: string}} labels。
 */
export function settingsFormLabels(t, failed, unavailableKey) {
  return {
    save: t('form.save'), saving: t('form.saving'),
    saveFailed: failed === undefined ? '' : t('form.saveFailed', { message: failed }),
    readOnly: t('form.readOnly'), unavailable: t(unavailableKey),
  }
}
